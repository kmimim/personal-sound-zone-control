% ワークスペースの初期化
clear; clc; close all;

Nsrc = 1;         % 制御目標とする仮想的な音源の数（ここでは1つの平面波を想定）
ang_wave = pi/2;  % 音波が進んでくる方向 [rad]（pi/2 = 90度：真下から真上へ進む平面波）
amp_src = ones(1,Nsrc); % 仮想音源の振幅（1 = 基準振幅として設定）

freq = 1000;      % シミュレーションする音波の周波数 [Hz]
c = 340;          % 音速 [m/s]
k = 2*pi*freq/c;  % 波数 : 空間的な位相の変化率を表す物理量

% グラフ描画のフラグ
pltPos = true;    % pltPos = スピーカーとマイクの配置図
pltSPL = true;    % pltSPL = 空間全体の音圧レベル分布図

mthd_ctrl = "pm"; % 音場制御の手法 = PM法

%% -------------------------------------------------------------------------
%% スピーカーとマイクの配置
%% -------------------------------------------------------------------------

num_sp = 32;      % 使用するスピーカー数
y_center = 1.0; % 制御ゾーンの中心のy座標（スピーカーアレイからの高さ）
% --- ユーザー指定の範囲と間隔 ---
d1 = 1.0;         % width (x方向の幅)
d2 = 2.0;         % length (y方向の幅)
itv_x = 0.04;     % x方向の制御点間隔 [m] (4cm)
itv_y = 0.08;     % y方向の制御点間隔 [m] (8cm)

% 間隔から格子点数を自動計算 (端点を含むため +1 し、浮動小数の誤差を round で丸める)
n_x = round(d1 / itv_x) + 1; 
n_y = round(d2 / itv_y) + 1; 

% 外部関数 pos_sp_mic.m を呼び出し、座標と「実際に生成された総マイク数(num_mic)」を取得
[pos_sp, pos_mic, num_mic] = pos_sp_mic(num_sp, y_center, n_x, n_y, d1, d2, pltPos);

%% -------------------------------------------------------------------------
%% 自由空間の伝達関数計算 
%% -------------------------------------------------------------------------
% 外部関数 IR_freefield.m を呼び出し、各スピーカーから各マイクへの音の伝わり方を計算
% G_ctrl : 伝達関数行列[64マイク × 32スピーカー × 1周波数]
G_ctrl = IR_freefield(pos_mic, pos_sp, k);

%% -------------------------------------------------------------------------
%% フィルターの算出と音場制御
%% -------------------------------------------------------------------------
% 外部関数 filter_pm.m を呼び出し、PM法に基づいてスピーカーの駆動重みを計算
% drv : 各スピーカーに出力する複素数フィルター（振幅と位相の補正値）[32スピーカー × 1周波数]
drv = filter_pm(pos_mic, G_ctrl, freq, ang_wave, amp_src, Nsrc, c);

%% -------------------------------------------------------------------------
%% 制御結果の評価
%% -------------------------------------------------------------------------
% 各スピーカーの伝達関数にフィルターを掛け合わせ、制御点での合成音圧を計算
% p_ctrl : 64個のマイク位置における実際の合成複素音圧 [64行 × 1列]
p_ctrl = G_ctrl * drv;

% マイク群を「Bz」と「Dz」に半分ずつ分割
num_bz = num_mic / 2;          % BZのマイク数（32点）
p_bz = p_ctrl(1:num_bz);       % 前半1〜32点：BZの音圧
p_dz = p_ctrl(num_bz+1:end);   % 後半33〜64点：Dzの音圧

% ACの計算
% BZの平均音響エネルギーと、DZの平均音響エネルギーの比をデシベル(dB)で算出
% 値が大きいほど、2つのゾーン間の音の格差（遮音性能）が優れていることを示す
AC_freq = 10 * log10(sum(abs(p_bz).^2) ./ sum(abs(p_dz).^2));

% 各マイク位置における音圧レベル（SPL）をdBスケールに変換
SPL_ctrl = 10 * log10(abs(p_ctrl).^2);

%% -------------------------------------------------------------------------
%% 空間全体の音圧分布図の作成と結果表示 
%% -------------------------------------------------------------------------
% 保存する画像ファイル名の生成
map_name = sprintf("SPL_sp%d_mic%d_%dHz_center_%.2fm_AC=%.2f_%s.png", ...
                   num_sp, num_mic, freq, y_center, round(AC_freq), mthd_ctrl);

% 外部スクリプト spl_distribution.m を実行し、部屋全体の音圧分布をプロット・画像保存
run spl_distribution.m

% コマンドウィンドウに結果（周波数、スピーカー数、マイク数、ACの計算値）をテキスト表示
fprintf("f=%dHz, num_sp=%d, num_mic=%d, AC=%.3fdB\n", freq, num_sp, num_mic, AC_freq);