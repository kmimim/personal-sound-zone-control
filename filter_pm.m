function drv_ls = filter_pm(mic_geo, G, f, ang_wave, amp_src, Nsrc, c)

    % Gのサイズ取得
    % n_mic : 制御点(マイク)数
    % n_sp  : スピーカ数
    [n_mic, n_sp] = size(G,1:2);

    % 周波数ビン数
    f_len = length(f);

    % 出力用行列
    % 行：スピーカ
    % 列：周波数
    drv_ls = zeros(n_sp, f_len);

    % 周波数ごとに処理
    for kk = 1:f_len

        % 現在の周波数における伝達関数行列
        % サイズ: [マイク数 × スピーカ数]
        g = G(:,:,kk);

        %--------------------------------------------------
        % 正則化パラメータの計算
        %
        % 最大固有値の10^-5倍
        % 行列が悪条件になるのを防ぐ
        %--------------------------------------------------
        reg_para = 10^(-5) * eigs((g' * g), 1);

        % 固定値を使う場合
        % reg_para = 0.001;

        %--------------------------------------------------
        % Bright Zone の目標音圧生成
        %
        % 平面波
        %
        % p(x,y)
        % = A exp(jk(xcosθ + ysinθ))
        %--------------------------------------------------

        p_des_bz = amp_src .* exp( ...
            1i * (2*pi*f(kk)/c) * ...
            (mic_geo(1:n_mic/2,1)*cos(ang_wave) + ...
             mic_geo(1:n_mic/2,2)*sin(ang_wave)));

        %--------------------------------------------------
        % Dark Zone の目標音圧
        %
        % 音を聞こえなくしたいので0
        %--------------------------------------------------
        p_des_dz = zeros(n_mic/2, Nsrc);

        %--------------------------------------------------
        % 全制御点の目標音圧ベクトル
        %
        % 上半分 : Bright Zone
        % 下半分 : Dark Zone
        %--------------------------------------------------
        p_des = [p_des_bz;
                 p_des_dz];

        %--------------------------------------------------
        % 最小二乗法 (Pressure Matching)
        %
        % d = (GᴴG + λI)^(-1) Gᴴ p_des
        %
        % d : スピーカ駆動信号
        % λ : 正則化パラメータ
        %--------------------------------------------------
        drv_single = inv(g' * g + reg_para * eye(n_sp)) ...
                     * g' * p_des;

        % 周波数ごとの結果を保存
        drv_ls(:,kk) = drv_single;
    end

end