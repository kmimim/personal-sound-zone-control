# 伝達関数計算関数 G

function G = IR_freefield(mic_geo, sp_geo, k)
    % 入力引数:
    %   mic_geo : マイクの座標行列 [マイク数 × 2列(x, y)]
    %   sp_geo  : スピーカーの座標行列 [スピーカー数 × 2列(x, y)]
    %   k       : 波数の配列

    n_mic = size(mic_geo, 1); % マイクの総数を取得 (64点)
    n_sp = size(sp_geo, 1);   % スピーカーの総数を取得 (32台)

    %% ---------------------------------------------------------------------
    %% すべてのスピーカーとマイクの間の「直線距離」を計算
    %% ---------------------------------------------------------------------
    % 各マイクと各スピーカーの間の距離を格納する行列を初期化 [64行 × 32列]
    r_ctrl = zeros(n_mic, n_sp);
    
    % スピーカーの数だけループを回し、総当たりで距離を計算
    for ii = 1:n_sp
        x_sp = zeros(n_mic, 1); % 一時的なx座標格納用ベクトル
        y_sp = zeros(n_mic, 1); % 一時的なy座標格納用ベクトル

        % 現在注目しているスピーカー ii の (x, y) 座標をマイクの数だけ複製
        x_sp(:) = sp_geo(ii, 1);
        y_sp(:) = sp_geo(ii, 2);

        % 三平方の定理を用いて、スピーカー ii と全マイクの間の距離を一括計算
        r_col = sqrt( (x_sp - mic_geo(:,1)).^2 + (y_sp - mic_geo(:,2)).^2 );
        
        % スピーカーとマイクが完全に同じ位置(距離0)になった場合、分母分子の計算で無限大(エラー)に
        % なるのを防ぐため、極小の数値 (1e-4 = 0.1mm) で下限を設けて安全対策（クリッピング）をします
        r_col = max(r_col, 1e-4);
        
        % 計算した距離の列ベクトルを、距離行列の ii 番目の列に格納
        r_ctrl(:, ii) = r_col;
    end

    %% ---------------------------------------------------------------------
    %% 2次元波動方程式の基本解（グリーン関数）を用いて伝達関数を計算
    %% ---------------------------------------------------------------------
    % 伝達関数を格納する3次元行列を初期化 [マイク数 × スピーカー数 × 周波数長]
    G = zeros(n_mic, n_sp, length(k));
    
    % 周波数（波数 k）の数だけループ（今回のメイン処理では1回のみ）
    for kk = 1:length(k)
        % マイクのループ
        for ii = 1:n_mic
            % スピーカーのループ
            for jj = 1:n_sp
                
                % 【物理公式の適用】
                % 2次元自由空間における点音源（線音源）からの波動伝播の基本解を計算します。
                % 公式: G = (i / 4) * H0_1(k * r)
                %   1i         : MATLABにおける虚数単位 (i)
                %   besselh(0,1,...) : 第1種第0次のハンケル関数（複素数の波の広がりと減衰を表す）
                %   k(kk)      : 現在の周波数の波数
                %   r_ctrl(ii,jj) : 対象のマイクとスピーカーの間の直線距離
                G(ii, jj, kk) = (1i / 4) * besselh(0, 1, k(kk) * r_ctrl(ii, jj));
                
            end
        end
    end
end